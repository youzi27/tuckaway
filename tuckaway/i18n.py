LANG = "en"


def set_lang(lang):
    global LANG
    LANG = "zh" if str(lang).lower().startswith("zh") else "en"


def t(key, default=None, **kw):
    m = MESSAGES.get(key)
    if m is None:
        return default if default is not None else key
    s = m[0] if LANG == "zh" else m[1]
    if not kw:
        return s
    try:
        return s.format(**kw)
    except (KeyError, IndexError, ValueError):
        return s


